#!/usr/bin/env python3
"""Writes src/wosstart.c from startup/wosstart.o (the built-in startup)."""
import sys

src, dst = sys.argv[1], sys.argv[2]
data = open(src, "rb").read()
with open(dst, "w") as f:
    f.write("/* Generated by tools/bin2c.py from %s; do not edit. */\n"
            "#include <stddef.h>\n\n"
            "const unsigned char wosstart_o[] = {\n" % src)
    for i in range(0, len(data), 12):
        f.write("    " + ", ".join("0x%02x" % b for b in data[i:i + 12]) + ",\n")
    f.write("};\nconst size_t wosstart_o_len = %d;\n" % len(data))
